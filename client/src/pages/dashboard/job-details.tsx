import { useEffect, useMemo, useState } from "react";
import { Link, useRoute } from "wouter";
import { useMutation, useQuery } from "@tanstack/react-query";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Progress } from "@/components/ui/progress";
import { Textarea } from "@/components/ui/textarea";
import { apiRequest } from "@/lib/queryClient";
import type { FreelancerProfile, JobPost } from "@shared/schema";
import {
  ArrowLeft,
  Briefcase,
  Clock,
  Copy,
  DollarSign,
  ExternalLink,
  MapPin,
  RefreshCw,
  Sparkles,
} from "lucide-react";

type MessageType = "comment";

export default function JobDetails() {
  const [, params] = useRoute("/dashboard/jobs/:id");
  const [comment, setComment] = useState("");
  const [copied, setCopied] = useState(false);
  const [hasAutoGenerated, setHasAutoGenerated] = useState(false);

  const profileQuery = useQuery<FreelancerProfile>({
    queryKey: ["/api/profile"],
  });

  const jobsQuery = useQuery<{ jobs: JobPost[] }>({
    queryKey: ["/api/jobs"],
  });

  const jobId = params?.id ?? "";
  const job = jobsQuery.data?.jobs.find((item) => item.id === jobId);
  const profile = profileQuery.data ?? { intro: "", skills: [] };

  const matchedSkillNames = useMemo(() => {
    if (!job) return [];
    return profile.skills
      .map((skill) => skill.name)
      .filter((skill) =>
        job.matchedSkills.some(
          (matched) => matched.toLowerCase() === skill.toLowerCase()
        )
      );
  }, [job, profile.skills]);

  const matchScore = useMemo(() => {
    if (profile.skills.length === 0) return 0;
    return Math.round((matchedSkillNames.length / profile.skills.length) * 100);
  }, [matchedSkillNames.length, profile.skills.length]);

  const generateMutation = useMutation({
    mutationFn: async () => {
      if (!job) {
        return { message: "" };
      }
      const response = await apiRequest("POST", "/api/generate-message", {
        jobTitle: job.title,
        jobDescription: job.description,
        skills: matchedSkillNames,
        tone: "friendly",
        messageType: "comment" as MessageType,
        intro: profile.intro,
      });
      return response.json();
    },
    onSuccess: (data) => {
      setComment(data.message || "");
    },
  });

  useEffect(() => {
    if (!job || !profileQuery.data || hasAutoGenerated) {
      return;
    }
    generateMutation.mutate();
    setHasAutoGenerated(true);
  }, [job, profileQuery.data, hasAutoGenerated, generateMutation]);

  const handleCopy = async () => {
    if (!comment) return;
    await navigator.clipboard.writeText(comment);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  if (jobsQuery.isLoading || profileQuery.isLoading) {
    return (
      <div className="p-4 sm:p-6 lg:p-10 space-y-8 sm:space-y-10 lg:space-y-12 max-w-5xl mx-auto">
        <Card>
          <CardHeader>
            <CardTitle>Loading job details...</CardTitle>
          </CardHeader>
        </Card>
      </div>
    );
  }

  if (!job) {
    return (
      <div className="p-4 sm:p-6 lg:p-10 space-y-8 sm:space-y-10 lg:space-y-12 max-w-5xl mx-auto">
        <Card>
          <CardHeader>
            <CardTitle>Job not found</CardTitle>
            <CardDescription>
              The job you are looking for may have been removed.
            </CardDescription>
          </CardHeader>
          <CardContent>
            <Button asChild variant="outline">
              <Link href="/dashboard/jobs">
                <ArrowLeft className="w-4 h-4 mr-2" />
                Back to jobs
              </Link>
            </Button>
          </CardContent>
        </Card>
      </div>
    );
  }

  return (
    <div className="p-4 sm:p-6 lg:p-10 space-y-8 sm:space-y-10 lg:space-y-12 max-w-5xl mx-auto">
      <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between flex-wrap">
        <div className="space-y-1">
          <Button asChild variant="ghost" className="px-0 text-muted-foreground">
            <Link href="/dashboard/jobs">
              <ArrowLeft className="w-4 h-4 mr-2" />
              Back to jobs
            </Link>
          </Button>
          <h1 className="text-2xl font-bold" data-testid="text-job-details-heading">
            {job.title}
          </h1>
          <p className="text-muted-foreground flex items-center gap-2">
            <Briefcase className="w-4 h-4" />
            {job.source} • @{job.authorHandle || job.author}
          </p>
        </div>
        <Button asChild variant="outline" className="gap-2 w-full sm:w-auto">
          <a href={job.sourceUrl} target="_blank" rel="noopener noreferrer">
            <ExternalLink className="w-4 h-4" />
            View original post
          </a>
        </Button>
      </div>

      <Card>
        <CardHeader>
          <CardTitle className="text-lg">Opportunity details</CardTitle>
          <CardDescription>Review the job post and matching context.</CardDescription>
        </CardHeader>
        <CardContent className="space-y-5">
          <div className="flex flex-wrap gap-4 text-sm text-muted-foreground">
            <span className="flex items-center gap-2">
              <Clock className="w-4 h-4" />
              {job.postedAt}
            </span>
            {job.budget && (
              <span className="flex items-center gap-2 font-semibold text-foreground">
                <DollarSign className="w-4 h-4 text-primary" />
                {job.budget}
              </span>
            )}
            {job.isRemote && (
              <span className="flex items-center gap-2">
                <MapPin className="w-4 h-4" />
                Remote
              </span>
            )}
          </div>

          <p className="text-sm leading-relaxed text-muted-foreground whitespace-pre-line">
            {job.description}
          </p>

          <div className="flex flex-wrap gap-2">
            {job.matchedSkills.map((skill) => (
              <Badge key={skill} variant="secondary" className="rounded-md text-xs">
                {skill}
              </Badge>
            ))}
          </div>
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle className="text-lg">Skill match score</CardTitle>
          <CardDescription>
            Based on your saved skills compared to this opportunity.
          </CardDescription>
        </CardHeader>
        <CardContent className="space-y-4">
          <div className="flex items-center justify-between">
            <span className="text-sm font-medium">
              {matchedSkillNames.length} of {profile.skills.length} skills matched
            </span>
            <span className="text-sm font-semibold text-primary">{matchScore}%</span>
          </div>
          <Progress value={matchScore} className="h-2" />
          {profile.skills.length === 0 && (
            <p className="text-xs text-muted-foreground">
              Add skills in your profile to improve match scores.
            </p>
          )}
        </CardContent>
      </Card>

      <Card className="border-sidebar-border/60">
        <CardHeader>
          <CardTitle className="text-lg flex items-center gap-2">
            <Sparkles className="w-5 h-5 text-primary" />
            Auto-generated comment
          </CardTitle>
          <CardDescription>
            A short, human-friendly comment you can post right away.
          </CardDescription>
        </CardHeader>
        <CardContent className="space-y-4">
          <Textarea
            value={comment}
            onChange={(event) => setComment(event.target.value)}
            rows={6}
            className="resize-none text-sm leading-relaxed"
            placeholder="Generating a comment based on this job..."
            data-testid="textarea-job-comment"
          />
          <div className="flex flex-wrap gap-2">
            <Button
              onClick={() => generateMutation.mutate()}
              disabled={generateMutation.isPending}
              className="gap-2"
              data-testid="button-regenerate-comment"
            >
              {generateMutation.isPending ? (
                <RefreshCw className="w-4 h-4 animate-spin" />
              ) : (
                <RefreshCw className="w-4 h-4" />
              )}
              Regenerate comment
            </Button>
            <Button
              variant="outline"
              onClick={handleCopy}
              disabled={!comment}
              className="gap-2"
              data-testid="button-copy-comment"
            >
              <Copy className="w-4 h-4" />
              {copied ? "Copied!" : "Copy comment"}
            </Button>
          </div>
        </CardContent>
      </Card>
    </div>
  );
}
